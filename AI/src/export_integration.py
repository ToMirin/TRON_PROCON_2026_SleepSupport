"""AI-09 C export. Run from AI: python -m src.export_integration --help."""
from pathlib import Path
import argparse
import hashlib
import numpy as np

INPUT_SCALE = 0.021447716280817986
INPUT_ZERO_POINT = 2
OUTPUT_SCALE = 0.00390625
OUTPUT_ZERO_POINT = -128


def sha256_file(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def quantize_int8(x, scale=INPUT_SCALE, zero_point=INPUT_ZERO_POINT):
    """float32 division, ties-to-even BEFORE adding zero point; then saturate.

    Firmware must implement this rounding rule explicitly (C roundf differs).
    """
    x = np.asarray(x, dtype=np.float32)
    if not np.isfinite(x).all() or not np.isfinite(scale) or scale <= 0:
        raise ValueError('Nonfinite input or invalid scale')
    if int(zero_point) != zero_point or not -128 <= zero_point <= 127:
        raise ValueError('Invalid int8 zero point')
    with np.errstate(over='ignore'):
        q = np.rint(x / np.float32(scale)) + np.float32(zero_point)
    return np.clip(q, -128, 127).astype(np.int8)


def dequantize_int8(q, scale=OUTPUT_SCALE, zero_point=OUTPUT_ZERO_POINT):
    q = np.asarray(q)
    if q.dtype != np.int8 or not np.isfinite(scale) or scale <= 0:
        raise ValueError('Expected int8 and positive finite scale')
    return (q.astype(np.float32) - np.float32(zero_point)) * np.float32(scale)


def model_quantization(interpreter):
    ins, outs = interpreter.get_input_details(), interpreter.get_output_details()
    if len(ins) != 1 or len(outs) != 1:
        raise ValueError('Expected one input and one output')
    for detail, shape, scale, zp in (
        (ins[0], (1, 98, 40, 1), INPUT_SCALE, INPUT_ZERO_POINT),
        (outs[0], (1, 3), OUTPUT_SCALE, OUTPUT_ZERO_POINT),
    ):
        if tuple(detail['shape']) != shape or detail['dtype'] != np.int8:
            raise ValueError(f"Unexpected tensor: {detail['name']}")
        p = detail['quantization_parameters']
        if len(p['scales']) != 1 or len(p['zero_points']) != 1:
            raise ValueError('Only per-tensor quantization is supported')
        if float(p['scales'][0]) != scale or int(p['zero_points'][0]) != zp:
            raise ValueError('Model differs from frozen AI-08 quantization')
    return ins[0], outs[0]


def _array(name, values, shape):
    a = np.asarray(values, dtype=np.float32)
    if a.shape != shape or not np.isfinite(a).all():
        raise ValueError(f'Invalid {name}: {a.shape}; expected {shape}')
    # Nine significant decimal digits round-trip IEEE binary32, including 0/1.
    def literal(x):
        s = format(float(x), '.9g')
        return s + ('' if '.' in s or 'e' in s else '.0') + 'f'
    def row(v):
        return ', '.join(literal(x) for x in v)
    if a.ndim == 1:
        body = ',\n'.join('    ' + row(a[i:i+8]) for i in range(0, len(a), 8))
    else:
        body = ',\n'.join('    {' + row(v) + '}' for v in a)
    dims = ''.join(f'[{n}]' for n in shape)
    return f'static const float {name}{dims} = {{\n{body}\n}};\n'


def _write(path, body):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    guard = 'TRON_AI_' + path.name.upper().replace('.', '_')
    path.write_text(f'/* Generated by AI-09. Do not edit. */\n#ifndef {guard}\n#define {guard}\n\n{body}\n#endif\n', encoding='utf-8')
    return path


def export_normalization(path, mean, std):
    if np.any(np.asarray(std) < 1e-8):
        raise ValueError('std below AI-04 STD_EPS')
    return _write(path, '/* TRAIN-only AI-05 stats. (logmel[m] - mean[m]) / std[m] */\n'
                  + _array('tron_mean', mean, (40,)) + _array('tron_std', std, (40,)))


def export_hann(path, window):
    return _write(path, '#define TRON_SAMPLE_RATE 16000\n#define TRON_INPUT_SAMPLES 16000\n'
                  '#define TRON_FRAME_LENGTH 400\n#define TRON_FRAME_STEP 160\n'
                  '#define TRON_FFT_LENGTH 512\n#define TRON_NUM_FRAMES 98\n'
                  '/* Periodic Hann; no centering/padding; PCM / 32768.0f. */\n'
                  + _array('tron_hann_window', window, (400,)))


def export_mel(path, filterbank):
    return _write(path, '#define TRON_NUM_FFT_BINS 257\n#define TRON_NUM_MEL_BINS 40\n'
                  '#define TRON_LOG_FLOOR 1.0e-10f\n'
                  '/* HTK 60-8000 Hz, no area normalization. Row-major [fft_bin][mel_bin].\n'
                  '   mel[m] = sum_k(power[k] * tron_mel_filterbank[k][m]);\n'
                  '   logmel = 10.0f * log10f(fmaxf(mel, TRON_LOG_FLOOR)). */\n'
                  + _array('tron_mel_filterbank', filterbank, (257, 40)))


def export_quantization(path, interpreter):
    model_quantization(interpreter)
    return _write(path, '#define TRON_INPUT_SCALE 0.021447716280817986f\n'
                  '#define TRON_INPUT_ZERO_POINT 2\n#define TRON_OUTPUT_SCALE 0.00390625f\n'
                  '#define TRON_OUTPUT_ZERO_POINT (-128)\n'
                  '#define TRON_CLASS_OTHER 0\n#define TRON_CLASS_SNORE 1\n#define TRON_CLASS_COUGH 2\n'
                  '/* Input NHWC [1][98][40][1], output [1][3].\n'
                  '   q = clamp(ties_to_even(float32(x / scale)) + zero_point, -128, 127).\n'
                  '   Do not substitute roundf (ties away from zero).\n'
                  '   output = (int32(q) - zero_point) * scale. */\n')


def export_all(output_dir, stats_path, model_path):
    from . import preprocess as pp
    from .dataset import load_normalization_stats
    import tensorflow as tf
    expected = dict(SAMPLE_RATE=16000, INPUT_SAMPLES=16000, FRAME_LENGTH=400,
                    FRAME_STEP=160, FFT_LENGTH=512, NUM_FRAMES=98, NUM_MEL_BINS=40,
                    FMIN=60.0, FMAX=8000.0, LOG_FLOOR=1e-10, STD_EPS=1e-8)
    for name, value in expected.items():
        if getattr(pp, name) != value:
            raise ValueError(f'Preprocess specification mismatch: {name}')
    mean, std = load_normalization_stats(stats_path)
    interpreter = tf.lite.Interpreter(model_path=str(model_path))
    interpreter.allocate_tensors()
    model_quantization(interpreter)
    d = Path(output_dir)
    return [export_normalization(d / 'normalization_params.h', mean, std),
            export_hann(d / 'hann_window.h', pp.periodic_hann_window()),
            export_mel(d / 'mel_filterbank.h', pp.MEL_FILTERBANK),
            export_quantization(d / 'quantization_params.h', interpreter)]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--stats', required=True, type=Path)
    p.add_argument('--model', required=True, type=Path)
    p.add_argument('--output-dir', required=True, type=Path)
    args = p.parse_args()
    for path in export_all(args.output_dir, args.stats, args.model):
        print(path)


if __name__ == '__main__':
    main()
